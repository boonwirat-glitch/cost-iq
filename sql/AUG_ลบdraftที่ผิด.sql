-- ============================================================
-- บล็อก 1 — สำรองก่อน  ⚠ ห้ามข้ามบล็อกนี้
--
-- 44 แถวนี้เป็นหลักฐานชิ้นสุดท้ายของ upsell ก.ค. ฉบับเต็ม
-- (ไฟล์ R2 ของ ก.ค. ถูกทับไปแล้ว ไม่มีที่อื่นเก็บอีก)
--
-- ต้องเห็น: เลข 44
-- ============================================================

create table if not exists snap_aug_backup as
select * from commission_payout_snapshots where period_month = '2026-08';

select count(*) as ต้องได้44 from snap_aug_backup;




-- ============================================================
-- บล็อก 2 — ดูก่อนว่าจะลบอะไร (ยังไม่ลบ)
--
-- ต้องเห็น 7 แถว รวม 44 คน ยอดรวม 540,365:
--   kam       14 คน   180,195
--   sales     15 คน   153,855   ← ยังไม่ได้ตั้งกติกา
--   tl         2 คน   111,000
--   admin      7 คน    71,799   ← ยังไม่ได้ตั้งกติกา
--   sales_tl   2 คน    20,514   ← ยังไม่ได้ตั้งกติกา
--   pm         3 คน     3,002
--   ad         1 คน         0
--
-- ทุกแถวต้องเป็น draft (ไม่มี final แม้แถวเดียว) และ
-- "คำนวณเมื่อ" ต้องเป็น 2026-08-01T00:27 = หลักฐานว่าเป็นข้อมูล ก.ค.
-- ============================================================

select beneficiary_role as ตำแหน่ง,
       count(*) as คน,
       sum(payout_amount) as ยอด,
       min(snapshot_status) as สถานะ,
       min(breakdown->>'computed_at') as คำนวณเมื่อ
from commission_payout_snapshots
where period_month = '2026-08'
group by 1
order by ยอด desc;




-- ============================================================
-- บล็อก 3 — ลบ  ⚠ แก้ข้อมูลจริง
--
-- ต้องเห็น: Success. 44 rows
-- ============================================================

delete from commission_payout_snapshots
where period_month = '2026-08';




-- ============================================================
-- บล็อก 4 — ตรวจ (ไม่แก้อะไร)
--
-- ต้องเห็น 5 แถว ตรงกับคอลัมน์ "ต้องได้" ทุกบรรทัด:
--   ส.ค. เหลือกี่แถว        | 0      | ต้องได้ 0
--   ก.ค. ยอดรวม            | 309197 | ต้องได้ 309197  ← ต้องไม่ขยับแม้แต่บาท
--   ก.ค. แถว final         | 44     | ต้องได้ 44
--   มิ.ย. ยอดรวม           | 224622 | ต้องได้ 224622
--   พ.ค. ยอดรวม           | 145761 | ต้องได้ 145761
--
-- แล้วเข้าหน้า /nrr แท็บ Commission เลือก ส.ค. — ต้องเห็นตัวเลขสด
-- (มีป้าย "ประมาณการ") ไม่ใช่หน้าว่าง ถ้าเจอหน้าว่างให้บอกผม
-- ============================================================

select 'ส.ค. เหลือกี่แถว' as รายการ,
       (select count(*) from commission_payout_snapshots where period_month='2026-08') as ค่าที่ได้,
       0 as ต้องได้
union all
select 'ก.ค. ยอดรวม',
       (select sum(payout_amount) from commission_payout_snapshots where period_month='2026-07'), 309197
union all
select 'ก.ค. แถว final',
       (select count(*) from commission_payout_snapshots
        where period_month='2026-07' and snapshot_status='final'), 44
union all
select 'มิ.ย. ยอดรวม',
       (select sum(payout_amount) from commission_payout_snapshots where period_month='2026-06'), 224622
union all
select 'พ.ค. ยอดรวม',
       (select sum(payout_amount) from commission_payout_snapshots where period_month='2026-05'), 145761;




